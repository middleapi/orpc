import type { RPCJsonSerializationMeta } from '@orpc/client'
import type { PartialDeep, Public, Segment } from '@orpc/shared'
import { RPCJsonSerializer } from '@orpc/client'
import { stringifyJSON } from '@orpc/shared'

export interface OperationKeyPrefixOptions {
  /**
   * Prepended as the first element of the key when present.
   * Use this to avoid key conflicts when multiple router utils share the same client.
   */
  prefix?: string | undefined
}

export interface OperationKeyBaseOptions extends OperationKeyPrefixOptions {
  /**
   * Serializes inputs into JSON-compatible values when building keys,
   * and restores them in fetchers and subscribers.
   * Pass the serializer your link uses so custom types are supported.
   *
   * @default new RPCJsonSerializer()
   */
  serializer?: Public<RPCJsonSerializer> | undefined
}

export type OperationKeyOptions<TInput> = OperationKeyBaseOptions & {
  input?: PartialDeep<TInput> | undefined
}

type OperationKeyContent<TInput> = Omit<OperationKeyOptions<TInput>, keyof OperationKeyBaseOptions> & {
  /**
   * Serializer types of non-JSON values in `input`, keyed by their JSON-encoded path,
   * so inputs with the same JSON form (like a `Date` and its ISO string) produce different keys.
   * Keyed by path (not a list) so partial keys still match.
   */
  inputMeta?: Record<string, string[]> | undefined
}

export type OperationKey<TInput>
  = | [path: string[], options: OperationKeyContent<TInput>]
    | [prefix: string, path: string[], options: OperationKeyContent<TInput>]

const defaultSerializer = /* @__PURE__ */ new RPCJsonSerializer()

/**
 * Generate a **full matching** key for SWR operations.
 *
 * The input is serialized to JSON-compatible values, so keys hash and match
 * by value, including types like `Date`, `BigInt`, `Set`, `Map` and custom serializer types.
 *
 * @see {@link https://orpc.dev/docs/integrations/swr#key-serializer | SWR Integration - Key Serializer}
 */
export function generateOperationKey<TInput>(
  path: string[],
  options: OperationKeyOptions<TInput> = {},
): OperationKey<TInput> {
  return [
    ...options.prefix !== undefined ? [options.prefix] : [],
    path,
    {
      ...options.input !== undefined ? serializeInput(options.serializer ?? defaultSerializer, options.input) : {},
    },
  ] as OperationKey<TInput>
}

/**
 * Restore the input of a key generated by {@link generateOperationKey}.
 */
export function deserializeOperationKeyInput<TInput>(
  key: OperationKey<TInput>,
  serializer: Public<RPCJsonSerializer> = defaultSerializer,
): TInput {
  const { input, inputMeta } = key[key.length - 1] as OperationKeyContent<TInput>

  if (input === undefined || inputMeta === undefined) {
    /**
     * Input can be omitted from the key when it is undefined,
     * so we can safely cast it to TInput with an undefined fallback.
     */
    return input as TInput
  }

  const meta: RPCJsonSerializationMeta[] = []

  for (const [path, types] of Object.entries(inputMeta)) {
    const segments = JSON.parse(path) as Segment[]

    for (const type of types) {
      meta.push([type, ...segments])
    }
  }

  /**
   * Restore deeper values before their containers (as the serializer emits them),
   * since the path-keyed record does not keep the original order across paths.
   * The sort is stable, so types sharing a path keep their order.
   */
  meta.sort((a, b) => b.length - a.length)

  return serializer.deserializeJson({ json: input, meta }) as TInput
}

function serializeInput(serializer: Public<RPCJsonSerializer>, input: unknown) {
  const { json, meta } = serializer.serializeJson(input)

  if (!meta?.length) {
    return { input: json }
  }

  const inputMeta: Record<string, string[]> = {}

  for (const [type, ...segments] of meta) {
    (inputMeta[stringifyJSON(segments)] ??= []).push(type)
  }

  return { input: json, inputMeta }
}
