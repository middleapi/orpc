import type { Context } from '@orpc/server'
import type { StandardHandlerOptions, StandardHandlerPlugin, StandardHandlerRoutingInterceptor, StandardHandlerRoutingInterceptorOptions } from '@orpc/server/standard'
import type { Promisable, Value } from '@orpc/shared'
import type { StandardUrl } from '@standard-server/core'
import type { OpenRPCDocument } from '../types'
import { getTracer, matchesHttpPath, mergeHttpPath, ORPC_NAME, toArray, value } from '@orpc/shared'
import { getJsonRpcCall } from '../adapters/standard/call'

/**
 * The JSON-RPC method of OpenRPC Service Discovery.
 */
const RPC_DISCOVER_METHOD = 'rpc.discover'

export interface OpenRPCDiscoveryHandlerPluginOptions<T extends Context> {
  /**
   * A static or dynamic OpenRPC document to serve, e.g. one generated by `OpenRPCGenerator`.
   * Receives routing interceptor options when provided as a function.
   *
   * @remarks
   * **Note**: Memoize a generated document, a batch request can ask for it once per call.
   */
  spec: Value<Promisable<OpenRPCDocument>, [options: StandardHandlerRoutingInterceptorOptions<T>]>

  /**
   * Determines whether the document is allowed to be served for a request.
   * When it resolves to `false`, the request falls through as if the plugin were not installed:
   * `rpc.discover` is answered with "Method not found" and the GET request stays unmatched.
   * Useful for restricting access to authenticated users.
   */
  allow?: Value<Promisable<boolean>, [options: StandardHandlerRoutingInterceptorOptions<T>]> | undefined

  /**
   * The URL path, relative to the handler prefix, at which to also serve the document over GET,
   * or `false` to only answer `rpc.discover`.
   *
   * @default '/openrpc.json'
   */
  specPath?: StandardUrl | false | undefined
}

/**
 * Answers OpenRPC Service Discovery, the `rpc.discover` JSON-RPC method, with the OpenRPC document,
 * and also serves the document over GET.
 *
 * @remarks
 * **Note**: `rpc.discover` is answered on `OpenRPCHandler`, and is never routed to a procedure or listed in the document's `methods`.
 * Other handlers, such as `RPCHandler` and `OpenAPIHandler`, only serve the document over GET.
 *
 * @see {@link https://orpc.dev/docs/openrpc/specification#service-discovery | OpenRPC Specification - Service Discovery}
 */
export class OpenRPCDiscoveryHandlerPlugin<T extends Context> implements StandardHandlerPlugin<T> {
  name = '~openrpc-discovery'

  private readonly spec: OpenRPCDiscoveryHandlerPluginOptions<T>['spec']
  private readonly allow: OpenRPCDiscoveryHandlerPluginOptions<T>['allow']
  private readonly specPath: Exclude<OpenRPCDiscoveryHandlerPluginOptions<T>['specPath'], undefined>

  constructor(options: OpenRPCDiscoveryHandlerPluginOptions<T>) {
    this.spec = options.spec
    this.allow = options.allow
    this.specPath = options.specPath ?? '/openrpc.json'
  }

  init(options: StandardHandlerOptions<T>): StandardHandlerOptions<T> {
    const routingInterceptor: StandardHandlerRoutingInterceptor<T> = async ({ next, ...interceptorOptions }) => {
      const { request, prefix } = interceptorOptions
      const call = getJsonRpcCall(request)

      // only the sub-requests of OpenRPCHandler are marked, so a raw HTTP request never reaches this branch
      if (call?.method === RPC_DISCOVER_METHOD) {
        if (await value(this.allow, interceptorOptions) === false) {
          return next()
        }

        const span = getTracer()?.getActiveSpan()
        span?.updateName(RPC_DISCOVER_METHOD)
        span?.setAttribute('rpc.system', ORPC_NAME)
        span?.setAttribute('rpc.method', RPC_DISCOVER_METHOD)

        // params are ignored, the method takes none
        const spec = await value(this.spec, interceptorOptions)

        return { matched: true, response: { status: 200, headers: {}, body: { result: spec } } }
      }

      const result = await next()

      if (
        result.matched
        // the GET endpoint is for raw HTTP requests only, never for a JSON-RPC call
        || call !== undefined
        || request.method !== 'GET'
        || this.specPath === false
      ) {
        return result
      }

      const specPath = prefix ? mergeHttpPath(prefix, this.specPath) : this.specPath

      if (!matchesHttpPath(request.url, specPath)) {
        return result
      }

      if (await value(this.allow, interceptorOptions) === false) {
        return result
      }

      /**
       * The request url is excluded because span names should have low cardinality,
       * so only the configured path is used.
       */
      getTracer()?.getActiveSpan()?.updateName(`${request.method} ${specPath} (openrpc spec)`)

      const spec = await value(this.spec, interceptorOptions)

      return { matched: true, response: { status: 200, headers: {}, body: spec } }
    }

    return {
      ...options,
      // Run after user-provided routing interceptors so they can capture the document responses
      routingInterceptors: [...toArray(options.routingInterceptors), routingInterceptor],
    }
  }
}
